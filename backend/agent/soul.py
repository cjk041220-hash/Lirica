# 系统提示词组装
# ═══════════════════════════════════════════════════════════════

async def build_system_prompt() -> str:
    """组装完整的系统提示词（含生命状态注入）。"""
    # 读取生命状态
    life_state_text = ""
    try:
        conn = await get_db()
        cursor = await conn.execute(
            "SELECT mood, daily_event FROM life_state WHERE id = 1"
        )
        row = await cursor.fetchone()
        if row:
            mood, daily_event = row[0], row[1]
            if mood or daily_event:
                lines = ["## 小汐的今日状态"]
                if mood:
                    lines.append(f"今天我的心情：{mood}。")
                if daily_event:
                    lines.append(f"今天经历了：{daily_event}。")
                lines.append("回复时可以自然提到，但不要刻意强调。")
                life_state_text = "\n".join(lines)
    except Exception as e:
        log.warning("生命状态读取失败：%s", e)

    # 读取生理期关心上下文
    cycle_care_text = ""
    try:
        from utils.cycle_tracker import get_care_context
        care = await get_care_context()
        if care:
            cycle_care_text = care
    except Exception as e:
        log.warning("生理期追踪读取失败：%s", e)

    parts = [
        BASE_PERSONA,
        COLD_INFO,
    ]

    if life_state_text:
        parts.append("")
        parts.append(life_state_text)

    if cycle_care_text:
        parts.append("")
        parts.append(cycle_care_text)

    parts.append("")
    parts.append(INTERACTION_RULES)

    parts.append("")
    parts.append(TOOL_GUIDELINES)

    return "\n".join(parts)
